"""业务参数中心 —— 全项目所有「可调节的数字」都放在这里。

为什么需要这个文件：

    R5 要做五个加分项，其中四个涉及时间与阈值：
        转正确认超时 15 分钟、退号冷却 10 分钟、取消时限 2 小时、
        爽约 2 次自动拉黑、上午 8 点开诊……

    这些数字若散落在各自的业务代码里，早晚会出事：
    两个地方都写着 15，改了其中一个忘了另一个，
    结果是「提示语说 15 分钟，实际 20 分钟才超时」——
    **而这类 bug 不会报错，它只是让系统说的话和做的事对不上。**

    把它们集中到一个文件，改阈值这件事就只剩「改这一行」，
    读代码的人也能一眼看到整套规则的全貌，不用去五个文件里考古。

本文件只放常量与纯函数，不做任何 IO、不 import 任何模块。
与 slot_status.py（状态与文案中心）是同一类东西，只是管的维度不同：
那边管「叫什么」，这里管「是多少」。
"""

from __future__ import annotations

# ------------------------------------------------------------
# 时段 → 开诊时刻
#
# 为什么需要它：取消时限要算「距离开诊还有多久」，
# 而库里只存了 morning / afternoon / evening 这种枚举，没有具体钟点。
#
# 为什么是「开诊时刻」而不是「开诊时段的中点」：
# 退号的截止本来就该以「这个时段什么时候开始叫号」为准，
# 拿中点（比如上午算 10:30）会让 8 点的号在 8:30 还能退，
# 而那时医生已经在看 1 号了。
# ------------------------------------------------------------
PERIOD_START_TIMES = {
    "morning": "08:00",
    "afternoon": "14:00",
    "evening": "18:30",
}

# 兜底值：万一排班里混入了契约外的时段，用它而不是抛异常。
# 与 slot_status.period_label 的 get 兜底是同一个考虑 ——
# 一个脏数据不该让整个列表页 500。
DEFAULT_PERIOD_START = "08:00"


def period_start_time(period: str) -> str:
    """时段 → 当天的开诊时刻（`"08:00"` 这种形式）。"""
    return PERIOD_START_TIMES.get(period, DEFAULT_PERIOD_START)


# ------------------------------------------------------------
# 五个加分项的阈值
# ------------------------------------------------------------

# 加分项 2：候补转正后，多久之内必须确认。
# 定 15 分钟的考量：太短，患者没看到通知就过期了，等于惩罚了守规矩的人；
# 太长，一个号被"待确认"钉住太久，后面排队的人干等 ——
# 而这个号在队列被卡住的整个期间是**谁也拿不到**的。
# 15 分钟是"来得及看一眼手机"与"不至于卡死队列"之间的折中。
CONFIRM_TIMEOUT_MINUTES = 15

# 加分项 1：退号之后，多久之内不能再约同一个排班。
# 目的不是惩罚退号（退号是正当权利），而是压住「反复退了抢、抢了退」
# 这种把号源当筹码来回倒的刷号行为。
# 10 分钟足够让"手抖退错号"的人无法立刻抢回来吗？——不能，
# 但那类人本来就该重新排队，而不是享受"刚退的号还在"的特权。
CANCEL_COOLDOWN_MINUTES = 10

# 加分项 4：开诊前多久停止自助取消。
# 留给医生与分诊台一点反应时间：
# 临近开诊时的空号，已经来不及再递补给候补者（他赶不过来），
# 不如让它干脆空着，也不让患者在开诊前 5 分钟随手退掉。
CANCEL_CUTOFF_MINUTES = 120

# 加分项 3：签到从什么时候开放。
# 就诊当天才开放，且只认日期不认钟点 ——
# 真实挂号系统里，早上 7 点来签到等 8 点开诊是完全正常的。
# 愿意提前到的人不该被系统拦在门外。
CHECKIN_SAME_DAY_ONLY = True

# 加分项 3/5：爽约累计多少次自动拉黑。
# 定为 2 次：1 次可能是忘了、堵车、临时有事，属于正常波动；
# 连着 2 次说明这个账号的预约已经不具备可信度，
# 而号源是稀缺资源，占着不来等于让别人看不上病。
NO_SHOW_BLACKLIST_THRESHOLD = 2
