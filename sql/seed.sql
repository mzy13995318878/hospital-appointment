-- 13a. 背景预约（约 650 条，CTE 批量生成）
--
--    为什么每位背景用户只发一条预约：
--      「同一天同一科室限 1 个号」是必做项里的硬规则。
--      虽然种子数据是直接写库、绕过了这条校验，
--      但如果造出「同一用户同一天约了骨科上午和骨科下午」这种数据，
--      评委点开「我的预约」就会看到系统自相矛盾。
--      一人一条是成本最低、也最贴近真实的解法 ——
--      绝大多数患者本来也就只看一个科。
--
--    **全文件最要紧的一处约束**：booked_count 必须与实际预约记录数严格相等。
--      库里的 CHECK(booked_count <= total_slots) 只管上界，
--      不管它跟记录数对不对得上。若两边对不上，
--      「剩余号源」就算错了，而页面显示完全正常 ——
--      这种 bug 只有在核对总数时才会暴露。
--      所以这里**绝不自己另算一遍占用数，而是直接从 schedules 原样读出来**，
--      让排班表与预约表共用同一个数字。
-- ------------------------------------------------------------
WITH RECURSIVE
  -- 只处理背景排班：id > 8 是 4b 生成的，
  -- 4a 那 8 条演示排班的预约已在第 5–10 节逐行写死。
  load AS (
      SELECT id AS sid, booked_count AS cnt
        FROM schedules
       WHERE id > 8
         AND booked_count > 0
  ),
  -- 累加窗口求每条排班的「用户段起点」：
  -- 第 n 条排班从「前面所有排班用掉的人数之后」开始取人。
  -- 首行的前置和为 NULL，用 COALESCE 兜成 0。
  cum AS (
      SELECT sid, cnt,
             COALESCE(SUM(cnt) OVER (
                 ORDER BY sid
                 ROWS BETWEEN UNBOUNDED PRECEDING AND 1 PRECEDING
             ), 0) AS base
        FROM load
  ),
  -- 序号发生器：单条排班最多 35 个号（号源上限），生成到 40 留足余量
  tick(k) AS (
      SELECT 1
      UNION ALL
      SELECT k + 1 FROM tick WHERE k < 40
  )
INSERT INTO appointments (id, user_id, schedule_id, seq_no, status, source,
                          created_at)
SELECT
    -- 预约 id 从 69 开始全局连续，不与第 5–12 节的 1–68 冲突
    68 + c.base + t.k,
    -- 背景用户从 id 71 开始，一人一条、全局不重复。
    --
    -- **为什么起点是 71 而不是 12**：第 5–10 节的演示预约已经用掉了
    -- 用户 1–70（排班 1 用到 15、排班 2 用到 40、排班 3 用到 52、
    -- 排班 4 用到 64、排班 5 用到 67、排班 6 用到 70），
    -- 其中 12 以后本来就是背景用户池里的人。
    -- 背景预约若再从 12 开始分配，这几位就会「既在演示排班持号、
    -- 又在背景排班持号」，两条排班一旦撞上同一天同一科室，
    -- 就违反了必做项 5 —— 本次正是靠 reset_db.py 的自洽性校验抓到的。
    --
    -- 70 这个数与第 5–10 节的写法强耦合，改了演示排班的持号人
    -- 必须回来核对。之所以不写成 (SELECT MAX(user_id) FROM appointments)
    -- 动态取，是因为 INSERT ... SELECT 里的子查询在边插边读时结果会漂移；
    -- 宁可用一个写死的常量，再由 reset_db.py 的校验兜底。
    70 + c.base + t.k,
    c.sid,
    t.k,                       -- seq_no 从 1 号开始连续发放
    'booked',
    'direct',
    -- 每条排班的预约时间整体错开（靠 sid 偏移），
    -- 否则所有排班的 1 号都是「同一分钟约的」，一眼假
    datetime('now', 'localtime',
             '-' || (600 + c.sid * 7 - t.k * 3) || ' minutes')
  FROM cum c
  JOIN tick t ON t.k <= c.cnt
 ORDER BY c.sid, t.k;

-- ------------------------------------------------------------
-- 13b. 背景候补队列（给满号的背景排班补上排队的人）
--
--    真实医院里，热门号满号之后一定有人在排队等退号。
--    若只造「已满」却不造排队，号源列表会显得像「没人要的满号」，
--    候补功能在数据上也就成了摆设。
--
--    排队人数取 1–3 人（用 sid 取模），每条排班的队列各自独立编号：
--    waitlist 的 UNIQUE(schedule_id, position) 是**按排班**约束的，
--    所以 position 必须在同一排班内唯一，跨排班可以从 1 重新开始。
--
--    排队者从「约上号的人」之后接着取，因此绝不会与 13a 的持号人重复 ——
--    一个人不会既持有这个号又在等这个号。
-- ------------------------------------------------------------
WITH RECURSIVE
  full_sch AS (
      SELECT id AS sid,
             1 + (id * 3) % 3 AS queue_len
        FROM schedules
       WHERE id > 8
         AND booked_count = total_slots   -- 只有真正满号的排班才有人排队
         AND is_closed = 0                -- 停诊的排班没人排
         -- 只给约一半的满号排班安排排队。
         -- 若全都排上队，列表里会清一色「候补中」，「已满」反而绝迹；
         -- 真实医院里号满了但暂时没人等的情况同样常见，
         -- 而且演示时要让评委一眼看出「候补中」是个特殊状态，不是常态。
         AND (id * 7) % 2 = 0
  ),
  tick(k) AS (
      SELECT 1
      UNION ALL
      SELECT k + 1 FROM tick WHERE k < 3
  )
INSERT INTO waitlist (id, user_id, schedule_id, position, status, joined_at)
SELECT
    -- waitlist id 从 3 开始：1、2 号位已被第 11 节的演示候补占用
    2 + ROW_NUMBER() OVER (ORDER BY f.sid, t.k),
    -- 紧接在 13a 用掉的最后一个用户之后取人
    (SELECT MAX(user_id) FROM appointments) + ROW_NUMBER() OVER (ORDER BY f.sid, t.k),
    f.sid,
    t.k,
    'waiting',
    datetime('now', 'localtime', '-' || (300 - t.k * 5) || ' minutes')
  FROM full_sch f
  JOIN tick t ON t.k <= f.queue_len
 ORDER BY f.sid, t.k;
