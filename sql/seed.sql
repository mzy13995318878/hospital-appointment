-- ============================================================
-- 演示数据（答辩用）
-- ------------------------------------------------------------
-- 本文件由 scripts/reset_db.py 在 sql/schema.sql 之后执行。
-- 反复执行前，reset_db.py 会先删掉整个数据库文件，因此这里
-- 直接 INSERT 即可，不需要处理重复数据。
--
-- 四条设计原则：
--
-- 1. 日期全部动态生成，不写死。
--    SQLite 的 date('now') 返回 UTC 日期，在东八区会有跨日偏差，
--    因此必须带 'localtime' 修饰符，否则凌晨时段会算成前一天。
--    好处：任何时候重建数据库，演示数据都落在未来，
--    将来若要加「不能预约过去日期」的校验，不会被自己的种子数据坑到。
--
-- 2. 号源分两档，不搞一刀切。
--    演示排班（会演示满 / 候补 / 递补的那几条）保持 12 个号，
--    这样打开弹窗能一眼看到全部持号人，评委能亲眼验证
--    「1 号从张三变成赵六」；
--    背景排班放到 15–30 个号，负责营造真实感。
--    真实感来自「科室数 × 医生数 × 排班天数」的覆盖面，不是单一号源的大小。
--
-- 3. 大量数据用递归 CTE 批量生成，不手写。
--    几百位用户和几百条预约如果逐行手写，文件会膨胀到几千行且无法维护。
--    这里用 WITH RECURSIVE 配合取模运算造出互不重复的姓名、身份证与手机号。
--
-- 4. 【最重要】演示数据与背景数据严格分开，且背景数据只做追加。
--    排班 1–8、预约 1–68、用户 1–11 是答辩现场要操作的靶子，
--    它们的 id 与语义写死，后续任何“扩充真实感”的改动都**只允许往后追加**，
--    不许回头改。理由很实在：docs/DEMO.md 的台本和
--    scripts/verify_demo.py 的 17 项自检都是照着这些 id 写的，
--    改一次就得同步三处，而这三处里只要漏一处，
--    就会变成“台上演示到一半发现和文档对不上”。
--
--    所以本文件的结构永远是：
--        第 1–3 节：写死的演示数据（医生 1–6 / 用户 1–11）
--        第 4 节起：追加的背景数据（医生 7+ / 用户 12+ / 排班 9+）
-- ============================================================

