-- 3. 背景用户（800 位，递归 CTE 批量生成）
--
--    位数定成 800 的依据：第 10b 节的背景预约**一位用户只占一条**，
--    所以用户数必须先给预约数留出余量。估算见第 10b 节的注释，
--    那里算出来的需求是 670 上下，这里取 800 留足富余。
--    （多出来的一百多位就是「注册了但没约号」的人，真实得很。）
--
--    姓名不重复的原理：
--      姓取 ((n-1)*7) % 30，名取 ((n-1)*11) % 31。
--      7 与 30 互质、11 与 31 互质，所以序数对 (姓, 名) 的循环周期
--      是 lcm(30, 31) = 930。
--      我们只取前 800 个，小于 930，因此姓名两两不重复。
--      若改成顺序取值（姓、名都从 0 开始等距取），
--      前 30 个就会变成「王伟、李芳、张娜……」这种一眼假的排列 ——
--      取模步长的意义就在于把这种规律性打散。
--
--    为什么名池长度必须用质数（这里是 31）而不是合数：
--      上一版用的是 28，lcm(30, 28) = 420 —— 30 和 28 不互质，
--      公约数 2 白白吃掉了一半的周期。当时只造 59 位用户，
--      420 的余量绰绰有余；但一旦扩到几百位就会撞名。
--      换成质数 31 之后，它与 30 必然互质，周期直接拉满到 30 × 31 = 930。
--      **改数据规模时，先回头检查生成算法的周期够不够** ——
--      这类「扩容就露馅」的问题在小数据量下完全看不出来。
--
--    身份证后 4 位与手机号同样用序号偏移生成，保证唯一且长度合规：
--      id_card_last4 = 1000 + n，取 1001–1800，恒为 4 位；
--      phone = 1382 + 2,000,001 + n，恒为 11 位。
-- ------------------------------------------------------------
WITH RECURSIVE seq(n) AS (
    SELECT 1
    UNION ALL
    SELECT n + 1 FROM seq WHERE n < 800
)
INSERT INTO users (id, name, id_card_last4, phone)
SELECT
    11 + n,
    substr('王李张刘陈杨黄赵吴周徐孙马朱胡林郭何高罗郑梁谢宋唐许邓冯韩曹曾彭',
           ((n - 1) * 7) % 30 + 1, 1)
    || substr('伟芳娜秀英敏静丽强磊洋艳勇军杰娟涛明超兰霞平刚桂建华文辉玉梅燕',
              ((n - 1) * 11) % 31 + 1, 1),
    printf('%04d', 1000 + n),
    '1382' || printf('%07d', 2000000 + n)
FROM seq;

