-- ------------------------------------------------------------
-- 4b. 背景排班（约 59 条，CTE 批量生成）
--
--    目的：让科室列表从「8 条排班的样例」变成「一家三甲医院的一周门诊表」。
--    覆盖 20 位医生 × 7 天，每天上午下午都有人出诊，
--    但**没有任何一位医生是天天出诊的** —— 真实医院的排班就是这样错落的。
--
--    **为什么从第 1 天（明天）开始，而不是从第 0 天（今天）开始：**
--      排班一旦开诊就不能再约（见 guards.py：距离开诊时间为负即拒绝）。
--      种子数据**无法预知建库时刻** —— 现在建库是深夜，
--      今天上午的号早就开诊了；换到凌晨建库，它又是可以约的。
--      同一份脚本跑出两种结果，正是第 4b 节开头极力避免的不可复现。
--      所以背景排班统一只造明天及以后 7 天的号：
--      这也正好对上真实医院「提前 7 天放号」的规则
--      （当天的号属于「当日挂号」，截止时间另算，不是同一条业务）。
--
--      今天的号源并未缺席 —— 排班 7 就是今天的，且刻意设为停诊。
--      停诊的号本来就约不了，不受开诊时间影响，
--      因此它是唯一一条「放在今天也不会因时刻不同而变脸」的排班。
--
--    三条生成规则，每条都只用整数取模，不用随机数：
--
--      是否出诊   (doc*3 + d) % 7 < 2       上午，约 7 天里出 2 天
--                (doc*5 + d*2) % 7 < 1     下午，约 7 天里出 1 天
--      号源总数   20 + (…) % 4 * 5          上午 20/25/30/35，下午再减 5
--      占用档位   (doc*11 + d*17) % 100     五档，见下面 final 的 CASE
--
--    用取模而不用随机数的理由很实在：**种子数据必须可复现**。
--    用随机的话，今天重建的库里 3 号是空的、明天重建就满了，
--    演示时照着文档点下去却发现状态对不上，这种问题根本没法排查。
--    取模是确定性的，任何人任何时候重建都得到同一份数据。
--
--    排班内部不会撞 UNIQUE(doctor_id, work_date, period)：
--    grid 里每个 (医生, 日期) 组合最多展开成上午、下午两行，天然唯一。
--    真正会撞的是与 4a 的手工排班 —— 比如 (医生 2, +1 天, 上午)
--    正好也是排班 8，所以下面必须用 NOT EXISTS 显式排除。
-- ------------------------------------------------------------
WITH RECURSIVE
  -- 7 天：明天(1) 到 +7 天。刻意不含今天(0)，理由见本节开头。
  -- 注意 d 仍要凑满 7 个连续值：出诊条件是对 7 取模的，
  -- 少了任何一个余数，某些医生就会「一周都不出诊」。
  day(d) AS (
      SELECT 1
      UNION ALL
      SELECT d + 1 FROM day WHERE d < 7
  ),
  -- 第一步：「医生 × 日期」的笛卡尔积，算出这一格的各项取模原材料。
  -- 这一步还不知道要不要出诊，只是把材料备齐，避免同一段表达式写两遍。
  grid AS (
      SELECT doc.id                          AS doc_id,
             day.d                           AS d,
             (doc.id * 3 + day.d) % 7        AS am_key,
             (doc.id * 5 + day.d * 2) % 7    AS pm_key,
             20 + ((doc.id * 7 + day.d * 3) % 4) * 5  AS total_slots,
             (doc.id * 11 + day.d * 17) % 100         AS load_key,
             (doc.id * 13 + day.d * 7) % 17           AS closed_key
        FROM doctors doc, day
  ),
  -- 第二步：把 grid 展开成「上午 / 下午」两倍的候选行，各自带独立的出诊条件。
  -- 下午的号源少 5 个（门诊下午号源普遍少于上午），
  -- 占用率与停诊的取模位置也各自错开，否则上下午会算出同一个占用档位。
  slots AS (
      SELECT doc_id, d, 'morning' AS period,
             total_slots,
             load_key,
             closed_key
        FROM grid
       WHERE am_key < 2
      UNION ALL
      SELECT doc_id, d, 'afternoon',
             total_slots - 5,
             (load_key + 7) % 100,
             (closed_key + 11) % 17
        FROM grid
       WHERE pm_key < 1
  ),
  -- 第三步：把取模值翻译成真实的号源占用。
  final AS (
      SELECT doc_id, d, period, total_slots,
             CASE WHEN closed_key = 0 THEN 1 ELSE 0 END AS is_closed,
             CASE
                 -- 停诊的排班一个人都约不出去，占用恒为 0
                 WHEN closed_key = 0 THEN 0
                 WHEN load_key < 30  THEN CAST(total_slots * 0.20 AS INTEGER)
                 WHEN load_key < 55  THEN CAST(total_slots * 0.35 AS INTEGER)
                 WHEN load_key < 78  THEN CAST(total_slots * 0.50 AS INTEGER)
                 WHEN load_key < 93  THEN CAST(total_slots * 0.65 AS INTEGER)
                 -- 最后一档直接满号：号源列表里得有「已满」的，
                 -- 全是「可约」的话，候补功能在数据上就成了摆设
                 ELSE total_slots
             END AS booked_count
        FROM slots
  )
INSERT INTO schedules (id, doctor_id, work_date, period, total_slots,
                       booked_count, is_closed)
SELECT
    -- id 从 9 开始顺延，绝不与 4a 的 1–8 撞
    8 + ROW_NUMBER() OVER (ORDER BY f.d, f.period, f.doc_id),
    f.doc_id,
    date('now', 'localtime', '+' || f.d || ' day'),
    f.period,
    f.total_slots,
    f.booked_count,
    f.is_closed
  FROM final f
 WHERE NOT EXISTS (
           SELECT 1 FROM schedules s
            WHERE s.doctor_id = f.doc_id
              AND s.work_date = date('now', 'localtime', '+' || f.d || ' day')
              AND s.period   = f.period
       )
 ORDER BY f.d, f.period, f.doc_id;

